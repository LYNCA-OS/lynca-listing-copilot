const outputPath = "lib/listing/cache/recognition-owner-source-manifest.mjs";

function sha256(value) {
  return crypto.createHash("sha256").update(value).digest("hex");
}

export async function buildRecognitionOwnerSourceManifest({ cwd = process.cwd() } = {}) {
  const entries = [];
  for (const path of recognitionDecisionOwnerSourcePaths) {
    const source = await readFile(resolve(cwd, path));
    entries.push({ path, sha256: sha256(source) });
  }
  const sourceHash = sha256(JSON.stringify(entries));
  return { entries, sourceHash };
}

export function renderRecognitionOwnerSourceManifest({ entries, sourceHash }) {
  return `// Generated by scripts/build-recognition-owner-source-manifest.mjs. Do not edit.\n`
    + `export const recognitionOwnerSourceManifestVersion = "recognition-owner-source-manifest-v1";\n`
    + `export const recognitionOwnerSourceManifestHash = ${JSON.stringify(sourceHash)};\n`
    + `export const recognitionOwnerSourceManifestEntries = Object.freeze(${JSON.stringify(entries, null, 2)});\n`;
}

export async function main(argv = process.argv.slice(2), { cwd = process.cwd() } = {}) {
  const rendered = renderRecognitionOwnerSourceManifest(await buildRecognitionOwnerSourceManifest({ cwd }));
  const target = resolve(cwd, outputPath);
  if (argv.includes("--check")) {
    const current = await readFile(target, "utf8").catch(() => "");
    if (current !== rendered) throw new Error("recognition_owner_source_manifest_stale");
    return { ok: true, mode: "check", path: outputPath };
  }
  await writeFile(target, rendered);
  return { ok: true, mode: "write", path: outputPath };
}

if (import.meta.url === pathToFileURL(process.argv[1] || "").href) {
  main().then((result) => {
    process.stdout.write(`${JSON.stringify(result)}\n`);
  }).catch((error) => {
    process.stderr.write(`${String(error?.message || error)}\n`);
    process.exitCode = 1;
  });
}
