#!/usr/bin/env node
// Reclaim disk on the production database, in the order that works when the
// disk is already full.
//
//   node scripts/reclaim-database-disk.mjs            (dry run: report only)
//   node scripts/reclaim-database-disk.mjs --apply \
//     --verified-export ~/lynca-telemetry/export-verification.json
//
// Written during an outage on 2026-07-27: a bounded catalog ingest ran on a
// free-tier project already at 1,381 MB against a 500 MB quota, filled the
// volume at roughly 60,000 rows, and Postgres stopped accepting connections.
// The deadlock is that freeing space needs a connection and the connection
// needs free space, so this exists ready to fire the moment one is available.
//
// ORDER MATTERS, for a reason that is easy to get wrong:
//
//   DELETE does not return space to the operating system. It marks tuples dead
//   and the file stays the same size, so on a full volume it achieves nothing
//   and costs WAL. Only TRUNCATE, DROP and VACUUM FULL shrink the file, and
//   VACUUM FULL rewrites the table, needing free space roughly equal to the
//   table it is compacting -- which is exactly what is missing.
//
// So: TRUNCATE the pure logs first, because it is instant and needs no
// headroom. That buys the room for VACUUM FULL to compact the tables that must
// keep their rows.
//
// Where the space went, measured before the outage:
//
//   catalog_import_staging        291 MB   105,558 rows, no inbound FKs
//   v4_recognition_sessions       227 MB     6,581 rows (~35 KB each)
//   catalog_cards                 204 MB   147,936 rows   <- the actual asset
//   v4_production_quality_ledger   72 MB
//   vector_query_logs              68 MB    14,079 rows
//   recognition_workflow_events    65 MB
//   v4_candidate_traces            63 MB
//   request_logs                   55 MB   127,142 rows
//
// The catalog is 204 MB of 1,348 MB. The rest is telemetry our own evaluation
// runs produced, which is the real finding: the quota was not consumed by the
// asset, it was consumed by exhaust that nothing prunes.

import { readFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import process from "node:process";
import { supabaseRestAdminHeaders } from "../lib/supabase-service-headers.mjs";

import {
  resolveSupabaseUrl,
  telemetryTables,
  telemetryVerificationContractVersion,
  verifyExport
} from "./export-telemetry-local.mjs";

// Resolved from the environment, never hardcoded. This is a destructive
// script whose safety gate asserts that the telemetry export it is about to
// act on belongs to the project being reclaimed; a literal ref here made that
// gate assert against a project that no longer exists.
const supabase = () => resolveSupabaseUrl();

function argValue(argv, name, fallback = "") {
  const index = argv.indexOf(name);
  return index >= 0 ? (argv[index + 1] ?? fallback) : fallback;
}

// Pure operational logs. Nothing references them, and they are regenerated by
// normal traffic, so the whole table goes.
const TRUNCATE_TABLES = [
  "request_logs",
  "vector_query_logs"
];

// Rows worth keeping, payloads that are not. Each entry blanks the heavy column
// on rows older than the window, then compacts the table.
const COMPACT = [
  {
    table: "catalog_import_staging",
    heavyColumns: ["raw_text"],
    keepDays: 0,
    why: "raw_text is the full extracted PDF of a checklist already promoted into catalog_cards; provenance stays in the other columns"
  },
  {
    table: "v4_recognition_sessions",
    heavyColumns: ["result", "payload"],
    keepDays: 3,
    why: "eval-run session payloads, ~35 KB each; recent ones are still being read by replay tooling"
  },
  {
    table: "v4_candidate_traces",
    heavyColumns: ["trace"],
    keepDays: 3,
    why: "candidate traces are diagnostic and re-derivable from a re-run"
  }
];

// The partial ingest that caused the outage. Tagged, so it comes out cleanly.
const ORPHAN_COHORT = "phoenix_slice_v1";

function headers(key, extra = {}) {
  return supabaseRestAdminHeaders(key, { "Content-Type": "application/json", ...extra });
}

async function rpcSql(key, sql) {
  // Supabase exposes no generic SQL endpoint over PostgREST; these statements
  // are printed for the operator to run in the SQL editor, which is also the
  // only surface available while the database refuses new client connections.
  return sql;
}

export function truncateStatements(tables = TRUNCATE_TABLES) {
  return tables.map((table) => `truncate table public.${table};`);
}

export function compactStatements(entries = COMPACT) {
  return entries.flatMap((entry) => {
    const set = entry.heavyColumns.map((column) => `${column} = null`).join(", ");
    const age = entry.keepDays > 0
      ? ` where created_at < now() - interval '${entry.keepDays} days'`
      : "";
    return [
      `-- ${entry.why}`,
      `update public.${entry.table} set ${set}${age};`,
      `vacuum full public.${entry.table};`
    ];
  });
}

export function orphanStatements(cohort = ORPHAN_COHORT) {
  return [
    `-- remove the partial ingest that filled the volume`,
    `delete from public.catalog_cards where metadata->>'ingest_cohort' = '${cohort}';`,
    `delete from public.catalog_products where metadata->>'ingest_cohort' = '${cohort}';`,
    `delete from public.catalog_sources where source_name = '${cohort}';`,
    `vacuum full public.catalog_cards;`
  ];
}

export function plan() {
  return [
    "-- 0. EXPORT FIRST. scripts/export-telemetry-local.mjs pulls these tables",
    "--    onto the local machine. Truncate is irreversible and these records",
    "--    are wanted; run the export to completion before anything below.",
    "",
    "-- 1. instant, needs no headroom: pure logs",
    ...truncateStatements(),
    "",
    "-- 2. remove the partial ingest",
    ...orphanStatements(),
    "",
    "-- 3. compact what must keep its rows",
    ...compactStatements()
  ];
}

export async function verifyReclaimGate(verificationPath) {
  const path = resolve(verificationPath);
  const saved = JSON.parse(await readFile(path, "utf8"));
  if (saved.schema_version !== telemetryVerificationContractVersion || saved.complete !== true) {
    throw new Error("telemetry export verification contract is incomplete or unsupported");
  }
  // Was `!== SUPABASE || !== defaultSupabaseUrl` -- two names for the same
  // literal, so the second clause could never fire. One comparison, against
  // the project this run actually targets.
  if (saved.project_url !== supabase()) {
    throw new Error("telemetry export verification belongs to a different Supabase project");
  }
  const required = new Set(telemetryTables.map(({ table }) => table));
  const present = new Set((saved.tables || []).map(({ table }) => table));
  for (const table of required) {
    if (!present.has(table)) throw new Error(`telemetry export verification missing ${table}`);
  }
  // Re-read every JSONL file and reproduce the digest. A saved report alone is
  // not authority to delete its source data.
  const verified = await verifyExport(dirname(path));
  if (verified.sha256 !== saved.sha256 || verified.total_rows !== saved.total_rows) {
    throw new Error("telemetry export verification digest changed since export");
  }
  return verified;
}

async function reachable(key) {
  try {
    const response = await fetch(`${supabase()}/rest/v1/catalog_cards?select=id&limit=1`, {
      headers: headers(key), signal: AbortSignal.timeout(10_000)
    });
    return response.ok;
  } catch {
    return false;
  }
}

export async function main(argv = process.argv.slice(2)) {
  const key = String(process.env.SUPABASE_SERVICE_ROLE_KEY || "").trim();
  const apply = argv.includes("--apply");
  const statements = plan();

  console.log(statements.join("\n"));

  if (!key) {
    console.log("\n-- SUPABASE_SERVICE_ROLE_KEY not set; printed the plan only");
    return 0;
  }
  const up = await reachable(key);
  console.log(`\n-- database reachable: ${up ? "yes" : "no"}`);
  if (!up) {
    console.log("-- run the statements above in the Supabase SQL editor once the project accepts connections");
    return 1;
  }
  if (!apply) {
    console.log("-- dry run; pass --apply once a SQL execution path is available");
    return 0;
  }
  const verificationPath = String(argValue(argv, "--verified-export", "")).trim();
  if (!verificationPath) {
    throw new Error("--apply requires --verified-export /path/to/export-verification.json");
  }
  const verified = await verifyReclaimGate(verificationPath);
  console.log(`-- local telemetry export verified: ${verified.total_rows} rows (${verified.sha256})`);
  // PostgREST cannot execute DDL. Kept explicit rather than pretending.
  console.log("-- PostgREST cannot run TRUNCATE or VACUUM; execute the statements above in the SQL editor");
  return 0;
}

if (process.argv[1] === new URL(import.meta.url).pathname) {
  main().then((c) => { process.exitCode = c; }).catch((e) => { console.error(e?.message || e); process.exitCode = 1; });
}
