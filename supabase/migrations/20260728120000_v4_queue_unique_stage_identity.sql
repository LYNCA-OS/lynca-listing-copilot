-- Recognition-triggered OCR enqueue has a stricter contract than the generic
-- pre-ingestion inserter: duplicate rows are executable only when they are
-- already queued/running/succeeded. A terminal row may be revived exactly
-- once per server-authorized recognition retry lineage; ordinary repeats and
-- active leases are never reset or double-run.
create or replace function public.enqueue_recognition_preingestion_ocr_jobs(
  p_jobs jsonb,
  p_authorized_retry_lineage_id text default null
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_job_count integer := case
    when pg_catalog.jsonb_typeof(p_jobs) = 'array' then pg_catalog.jsonb_array_length(p_jobs)
    else 0
  end;
  v_retry_lineage text := coalesce(nullif(pg_catalog.btrim(p_authorized_retry_lineage_id), ''), '');
  v_inserted integer := 0;
  v_requeued integer := 0;
  v_state_count integer := 0;
  v_runnable integer := 0;
  v_succeeded integer := 0;
  v_blocked_terminal integer := 0;
  v_identity_mismatch integer := 0;
begin
  if v_job_count < 1 or v_job_count > 32 then
    return pg_catalog.jsonb_build_object('saved', false, 'reason', 'ocr_job_request_invalid');
  end if;
  if v_retry_lineage <> '' and v_retry_lineage !~ '^[A-Za-z0-9][A-Za-z0-9_-]{0,159}$' then
    return pg_catalog.jsonb_build_object('saved', false, 'reason', 'authorized_retry_lineage_invalid');
  end if;
  if exists (
    select 1
    from pg_catalog.jsonb_array_elements(p_jobs) job_item
    where pg_catalog.jsonb_typeof(job_item) <> 'object'
       or nullif(pg_catalog.btrim(job_item ->> 'tenant_id'), '') is null
       or nullif(pg_catalog.btrim(job_item ->> 'asset_id'), '') is null
       or nullif(pg_catalog.btrim(job_item ->> 'bundle_id'), '') is null
       or nullif(pg_catalog.btrim(job_item ->> 'job_key'), '') is null
       or pg_catalog.btrim(job_item ->> 'job_key') !~ '^ocr:[A-Za-z0-9._-]+:[A-Za-z0-9._-]+:'
       or pg_catalog.lower(pg_catalog.btrim(job_item ->> 'job_type')) <> 'ocr_crop_verification'
       or pg_catalog.jsonb_typeof(job_item -> 'payload') <> 'object'
       or pg_catalog.btrim(job_item ->> 'bundle_id') !~* '^[0-9a-f]{8}-[0-9a-f]{4}-[1-8][0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$'
  ) then
    return pg_catalog.jsonb_build_object('saved', false, 'reason', 'ocr_job_identity_invalid');
  end if;
  if (
    select count(distinct pg_catalog.jsonb_build_array(
      pg_catalog.btrim(job_item ->> 'tenant_id'),
      pg_catalog.btrim(job_item ->> 'job_key')
    ))
    from pg_catalog.jsonb_array_elements(p_jobs) job_item
  ) <> v_job_count then
    return pg_catalog.jsonb_build_object('saved', false, 'reason', 'ocr_job_identity_duplicate');
  end if;

  with incoming as (
    select
      pg_catalog.btrim(job_item ->> 'tenant_id') as tenant_id,
      pg_catalog.btrim(job_item ->> 'job_key') as job_key,
      pg_catalog.btrim(job_item ->> 'asset_id') as asset_id,
      (pg_catalog.btrim(job_item ->> 'bundle_id'))::uuid as bundle_id,
      greatest(1, least(coalesce((job_item ->> 'priority')::integer, 40), 1000)) as priority,
      job_item -> 'payload' as payload
    from pg_catalog.jsonb_array_elements(p_jobs) job_item
  )
  select count(*)::integer
  into v_identity_mismatch
  from incoming
  join public.preingestion_jobs existing
    on existing.tenant_id = incoming.tenant_id
   and existing.job_key = incoming.job_key
  where existing.asset_id is distinct from incoming.asset_id
     or existing.bundle_id is distinct from incoming.bundle_id
     or existing.job_type is distinct from 'ocr_crop_verification';
  if v_identity_mismatch > 0 then
    raise exception using
      errcode = '23505',
      message = 'recognition_preingestion_ocr_job_identity_conflict';
  end if;

  with incoming as (
    select
      pg_catalog.btrim(job_item ->> 'tenant_id') as tenant_id,
      pg_catalog.btrim(job_item ->> 'job_key') as job_key,
      pg_catalog.btrim(job_item ->> 'asset_id') as asset_id,
      (pg_catalog.btrim(job_item ->> 'bundle_id'))::uuid as bundle_id,
      greatest(1, least(coalesce((job_item ->> 'priority')::integer, 40), 1000)) as priority,
      job_item -> 'payload' as payload
    from pg_catalog.jsonb_array_elements(p_jobs) job_item
  ), inserted as (
    insert into public.preingestion_jobs (
      tenant_id,
      job_key,
      asset_id,
      bundle_id,
      job_type,
      status,
      priority,
      payload,
      created_at,
      updated_at
    )
    select
      incoming.tenant_id,
      incoming.job_key,
      incoming.asset_id,
      incoming.bundle_id,
      'ocr_crop_verification',
      'queued',
      incoming.priority,
      incoming.payload,
      pg_catalog.clock_timestamp(),
      pg_catalog.clock_timestamp()
    from incoming
    on conflict (tenant_id, job_key) do nothing
    returning 1
  )
  select count(*)::integer into v_inserted from inserted;

  if v_retry_lineage <> '' then
    with incoming as (
      select
        pg_catalog.btrim(job_item ->> 'tenant_id') as tenant_id,
        pg_catalog.btrim(job_item ->> 'job_key') as job_key,
        pg_catalog.btrim(job_item ->> 'asset_id') as asset_id,
        (pg_catalog.btrim(job_item ->> 'bundle_id'))::uuid as bundle_id
      from pg_catalog.jsonb_array_elements(p_jobs) job_item
    ), requeued as (
      update public.preingestion_jobs existing
      set status = 'queued',
          attempts = 0,
          last_error = null,
          lease_owner = null,
          lease_expires_at = null,
          payload = existing.payload || pg_catalog.jsonb_build_object(
            'authorized_retry_lineage_id', v_retry_lineage
          ),
          updated_at = pg_catalog.clock_timestamp()
      from incoming
      where existing.tenant_id = incoming.tenant_id
        and existing.job_key = incoming.job_key
        and existing.asset_id = incoming.asset_id
        and existing.bundle_id = incoming.bundle_id
        and existing.job_type = 'ocr_crop_verification'
        and existing.status in ('failed', 'cancelled')
        and existing.lease_owner is null
        and existing.lease_expires_at is null
        and coalesce(existing.payload ->> 'authorized_retry_lineage_id', '') <> v_retry_lineage
      returning 1
    )
    select count(*)::integer into v_requeued from requeued;
  end if;

  with incoming as (
    select
      pg_catalog.btrim(job_item ->> 'tenant_id') as tenant_id,
      pg_catalog.btrim(job_item ->> 'job_key') as job_key,
      pg_catalog.btrim(job_item ->> 'asset_id') as asset_id,
      (pg_catalog.btrim(job_item ->> 'bundle_id'))::uuid as bundle_id
    from pg_catalog.jsonb_array_elements(p_jobs) job_item
  )
  select
    count(*)::integer,
    count(*) filter (where existing.status in ('queued', 'running'))::integer,
    count(*) filter (where existing.status = 'succeeded')::integer,
    count(*) filter (where existing.status in ('failed', 'cancelled'))::integer
  into v_state_count, v_runnable, v_succeeded, v_blocked_terminal
  from incoming
  join public.preingestion_jobs existing
    on existing.tenant_id = incoming.tenant_id
   and existing.job_key = incoming.job_key
   and existing.asset_id = incoming.asset_id
   and existing.bundle_id = incoming.bundle_id
   and existing.job_type = 'ocr_crop_verification';

  return pg_catalog.jsonb_build_object(
    'saved', v_state_count = v_job_count and v_blocked_terminal = 0,
    'reason', case
      when v_state_count <> v_job_count then 'ocr_job_state_missing'
      when v_blocked_terminal > 0 and v_retry_lineage = '' then 'ocr_terminal_retry_authorization_required'
      when v_blocked_terminal > 0 then 'ocr_authorized_retry_lineage_exhausted'
      else null
    end,
    'attempted_count', v_job_count,
    'inserted_count', v_inserted,
    'requeued_count', v_requeued,
    'runnable_count', v_runnable,
    'succeeded_count', v_succeeded,
    'blocked_terminal_count', v_blocked_terminal,
    'authorized_retry_lineage_applied', v_retry_lineage <> '' and v_requeued > 0
  );
end;
$$;

revoke all on function public.enqueue_recognition_preingestion_ocr_jobs(jsonb, text)
