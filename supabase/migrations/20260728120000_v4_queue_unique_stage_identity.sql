create or replace function public.claim_preingestion_recognition_commit_outbox(
  p_limit integer,
  p_lease_owner text,
  p_tenant_id text default null,
  p_asset_id text default null
)
returns setof public.preingestion_recognition_commit_outbox
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_limit integer := greatest(1, least(coalesce(p_limit, 4), 20));
  v_existing integer := 0;
begin
  if nullif(pg_catalog.btrim(p_lease_owner), '') is null
     or pg_catalog.length(p_lease_owner) > 160 then
    return;
  end if;

  -- A worker can disappear after consuming its final allowed attempt. Once
  -- that lease expires, make the terminal state explicit instead of leaving a
  -- permanently unclaimable `processing` row. The same guard also repairs any
  -- legacy queued row whose attempt budget was already exhausted.
  update public.preingestion_recognition_commit_outbox outbox
  set status = 'dead_letter',
      lease_owner = null,
      lease_expires_at = null,
      last_error = coalesce(outbox.last_error, 'lease_expired_after_max_attempts'),
      updated_at = pg_catalog.clock_timestamp()
  where outbox.attempts >= outbox.max_attempts
    and (
      (outbox.status = 'processing' and outbox.lease_expires_at <= pg_catalog.clock_timestamp())
      or outbox.status = 'queued'
    );

  -- An RPC response can be lost after the lease commits. Repeating the same
  -- request returns its existing lease instead of claiming/incrementing twice.
  return query
  select outbox.*
  from public.preingestion_recognition_commit_outbox outbox
  where outbox.status = 'processing'
    and outbox.lease_owner = p_lease_owner
    and outbox.lease_expires_at > pg_catalog.clock_timestamp()
    and (nullif(pg_catalog.btrim(p_tenant_id), '') is null or outbox.tenant_id = p_tenant_id)
    and (nullif(pg_catalog.btrim(p_asset_id), '') is null or outbox.asset_id = p_asset_id)
  order by outbox.outbox_id
  limit v_limit;
  get diagnostics v_existing = row_count;

  if v_existing >= v_limit then
    return;
  end if;

  return query
  with candidates as (
    select outbox.outbox_id
    from public.preingestion_recognition_commit_outbox outbox
    where (
        outbox.status = 'queued'
        or (
          outbox.status = 'processing'
          and outbox.lease_expires_at <= pg_catalog.clock_timestamp()
        )
      )
      and outbox.next_attempt_at <= pg_catalog.clock_timestamp()
      and outbox.attempts < outbox.max_attempts
      and (nullif(pg_catalog.btrim(p_tenant_id), '') is null or outbox.tenant_id = p_tenant_id)
      and (nullif(pg_catalog.btrim(p_asset_id), '') is null or outbox.asset_id = p_asset_id)
    order by outbox.next_attempt_at, outbox.created_at, outbox.outbox_id
    for update skip locked
    limit (v_limit - v_existing)
  )
  update public.preingestion_recognition_commit_outbox outbox
  set status = 'processing',
      attempts = outbox.attempts + 1,
      lease_owner = p_lease_owner,
      lease_expires_at = pg_catalog.clock_timestamp() + interval '90 seconds',
      updated_at = pg_catalog.clock_timestamp()
  from candidates
  where outbox.outbox_id = candidates.outbox_id
  returning outbox.*;
end;
$$;

create or replace function public.settle_preingestion_recognition_commit_outbox(
  p_outbox_id bigint,
  p_lease_owner text,
  p_completed boolean,
  p_error text default null,
  p_retry_after_seconds integer default 5
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_row public.preingestion_recognition_commit_outbox%rowtype;
begin
  update public.preingestion_recognition_commit_outbox outbox
  set status = case
        when p_completed then 'completed'
        when outbox.attempts >= outbox.max_attempts then 'dead_letter'
        else 'queued'
      end,
      next_attempt_at = case
        when p_completed then outbox.next_attempt_at
        else pg_catalog.clock_timestamp()
          + pg_catalog.make_interval(secs => greatest(1, least(coalesce(p_retry_after_seconds, 5), 3600)))
      end,
      lease_owner = null,
      lease_expires_at = null,
      last_error = nullif(pg_catalog.left(coalesce(p_error, ''), 500), ''),
      updated_at = pg_catalog.clock_timestamp()
  where outbox.outbox_id = p_outbox_id
    and outbox.status = 'processing'
    and outbox.lease_owner = p_lease_owner
  returning outbox.* into v_row;

  if found then
    return pg_catalog.jsonb_build_object(
      'settled', true,
      'outbox_id', v_row.outbox_id,
      'status', v_row.status,
      'attempts', v_row.attempts
    );
  end if;

  select outbox.* into v_row
  from public.preingestion_recognition_commit_outbox outbox
  where outbox.outbox_id = p_outbox_id;
  return pg_catalog.jsonb_build_object(
    'settled', v_row.outbox_id is not null and (
      (p_completed and v_row.status = 'completed')
      or (not p_completed and v_row.status in ('queued', 'dead_letter'))
    ),
    'outbox_id', p_outbox_id,
    'status', v_row.status,
    'attempts', v_row.attempts
  );
end;
$$;

