create or replace function public.enqueue_v4_recognition_batch_atomic(
  p_batch jsonb,
  p_jobs jsonb,
  p_operator_id text,
  p_sessions jsonb,
  p_tenant_id text
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_job_count integer := case
    when pg_catalog.jsonb_typeof(p_jobs) = 'array' then pg_catalog.jsonb_array_length(p_jobs)
    else 0
  end;
  v_distinct_job_id_count integer := 0;
  v_expected_outbox_count integer := 0;
  v_outbox_count integer := 0;
  v_result jsonb;
begin
  if pg_catalog.jsonb_typeof(p_jobs) <> 'array'
     or v_job_count < 1
     or v_job_count > 500 then
    return pg_catalog.jsonb_build_object('saved', false, 'reason', 'invalid_atomic_enqueue_request');
  end if;

  if exists (
    select 1
    from pg_catalog.jsonb_array_elements(p_jobs) job_item
    where pg_catalog.jsonb_typeof(job_item) <> 'object'
       or nullif(pg_catalog.btrim(job_item ->> 'id'), '') is null
       or nullif(pg_catalog.btrim(job_item ->> 'tenant_id'), '') is null
       or nullif(pg_catalog.btrim(job_item ->> 'operator_id'), '') is null
       or nullif(pg_catalog.btrim(job_item ->> 'recognition_session_id'), '') is null
       or nullif(pg_catalog.btrim(job_item ->> 'asset_id'), '') is null
       or nullif(pg_catalog.btrim(job_item ->> 'job_type'), '') is null
       or pg_catalog.jsonb_typeof(job_item -> 'payload') <> 'object'
       -- Expand-phase compatibility: old application instances do not yet
       -- send queue_decision_fingerprint. They keep using the audited legacy
       -- path during the rolling window. Once the new marker is present, the
       -- complete semantic identity is mandatory and fail-closed.
       or (
         nullif(pg_catalog.btrim(job_item -> 'payload' ->> 'queue_decision_fingerprint'), '') is not null
         and (
           nullif(pg_catalog.btrim(job_item -> 'payload' ->> 'image_generation_id'), '') is null
           or nullif(pg_catalog.btrim(job_item -> 'payload' ->> 'image_set_sha256'), '') is null
           or nullif(pg_catalog.btrim(job_item -> 'payload' ->> 'image_set_sha256'), '') !~ '^[0-9a-fA-F]{64}$'
           or nullif(pg_catalog.btrim(job_item -> 'payload' ->> 'queue_decision_fingerprint'), '') !~ '^[0-9a-fA-F]{64}$'
         )
       )
       or (
         nullif(pg_catalog.btrim(job_item -> 'payload' ->> 'authorized_retry_of_job_id'), '') is not null
         and (
           job_item -> 'payload' ->> 'authorized_retry_of_job_id'
             is distinct from job_item -> 'payload' ->> 'retry_of_job_id'
           or coalesce(job_item -> 'payload' ->> 'manual_retry', 'false') <> 'true'
         )
       )
  ) then
    return pg_catalog.jsonb_build_object('saved', false, 'reason', 'job_semantic_identity_invalid');
  end if;

  select count(distinct job_item ->> 'id')::integer
  into v_distinct_job_id_count
  from pg_catalog.jsonb_array_elements(p_jobs) job_item;
  if v_distinct_job_id_count <> v_job_count then
    return pg_catalog.jsonb_build_object('saved', false, 'reason', 'duplicate_job_id');
  end if;

  if exists (
    select 1
    from pg_catalog.jsonb_array_elements(p_jobs) job_item
    where nullif(pg_catalog.btrim(job_item -> 'payload' ->> 'queue_decision_fingerprint'), '') is not null
    group by
      p_tenant_id,
      p_operator_id,
      pg_catalog.btrim(job_item ->> 'asset_id'),
      pg_catalog.btrim(job_item -> 'payload' ->> 'image_generation_id'),
      pg_catalog.lower(pg_catalog.btrim(job_item -> 'payload' ->> 'image_set_sha256')),
      pg_catalog.lower(pg_catalog.btrim(job_item -> 'payload' ->> 'queue_decision_fingerprint')),
      pg_catalog.upper(pg_catalog.btrim(job_item ->> 'job_type')),
      coalesce(nullif(pg_catalog.btrim(job_item -> 'payload' ->> 'authorized_retry_of_job_id'), ''), '')
    having count(*) > 1
  ) then
    return pg_catalog.jsonb_build_object('saved', false, 'reason', 'duplicate_job_semantic_identity');
  end if;

  -- A moving model/catalog/worker revision may not be replayed from a terminal
  -- row. Keep the semantic identity occupied (so nonce changes cannot pay
  -- again) but fail closed until immutable revision readiness is restored.
  if exists (
    select 1
    from pg_catalog.jsonb_array_elements(p_jobs) job_item
    join public.v4_recognition_jobs existing_job
      on existing_job.id = job_item ->> 'id'
    where existing_job.status in ('L1_READY', 'L2_READY')
      and nullif(pg_catalog.btrim(job_item -> 'payload' ->> 'queue_decision_fingerprint'), '') is not null
      and coalesce(job_item -> 'payload' ->> 'queue_decision_replay_ready', 'false') <> 'true'
  ) then
    return pg_catalog.jsonb_build_object(
      'saved', false,
      'reason', 'queue_terminal_replay_revision_not_ready'
    );
  end if;

  select public.enqueue_v4_recognition_batch_atomic_impl_20260728(
    p_batch,
    p_jobs,
    p_operator_id,
    p_sessions,
    p_tenant_id
  ) into v_result;

  if coalesce((v_result ->> 'saved')::boolean, false) then
    select count(*)::integer
    into v_expected_outbox_count
    from (
      select 1
      from pg_catalog.jsonb_array_elements(p_jobs) job_item
      join pg_catalog.jsonb_array_elements(coalesce(v_result -> 'jobs', '[]'::jsonb)) result_item
        on result_item -> 'row' ->> 'id' = job_item ->> 'id'
      where coalesce((result_item ->> 'saved')::boolean, false)
        and pg_catalog.upper(coalesce(result_item -> 'row' ->> 'status', '')) in ('QUEUED', 'RETRYING', 'RUNNING')
        and nullif(pg_catalog.btrim(job_item -> 'payload' ->> 'image_generation_id'), '') is not null
        and nullif(pg_catalog.btrim(job_item -> 'payload' ->> 'image_set_sha256'), '') ~ '^[0-9a-fA-F]{64}$'
        and nullif(pg_catalog.btrim(job_item -> 'payload' ->> 'queue_decision_fingerprint'), '') ~ '^[0-9a-fA-F]{64}$'
      group by
        job_item ->> 'asset_id',
        pg_catalog.btrim(job_item -> 'payload' ->> 'image_generation_id'),
        pg_catalog.lower(pg_catalog.btrim(job_item -> 'payload' ->> 'image_set_sha256')),
        pg_catalog.lower(pg_catalog.btrim(job_item -> 'payload' ->> 'queue_decision_fingerprint')),
        coalesce(nullif(pg_catalog.btrim(job_item -> 'payload' ->> 'authorized_retry_of_job_id'), ''), '')
    ) eligible_outbox_groups;

    insert into public.preingestion_recognition_commit_outbox as outbox (
      tenant_id,
      asset_id,
      image_generation_id,
      image_set_sha256,
      queue_decision_fingerprint,
      identity_result_cache_key,
      identity_cache_image_generation_hash,
      identity_cache_read_allowed,
      writer_final_replay_allowed,
      authorized_retry_of_job_id,
      recognition_batch_id,
      recognition_job_id,
      status,
      next_attempt_at,
      updated_at
    )
    select
      p_tenant_id,
      job_item ->> 'asset_id',
      pg_catalog.btrim(job_item -> 'payload' ->> 'image_generation_id'),
      pg_catalog.lower(pg_catalog.btrim(job_item -> 'payload' ->> 'image_set_sha256')),
      pg_catalog.lower(pg_catalog.btrim(job_item -> 'payload' ->> 'queue_decision_fingerprint')),
      pg_catalog.lower(nullif(pg_catalog.btrim(job_item -> 'payload' ->> 'identity_result_cache_key'), '')),
      pg_catalog.lower(nullif(pg_catalog.btrim(job_item -> 'payload' ->> 'identity_cache_image_generation_hash'), '')),
      pg_catalog.lower(coalesce(
        job_item -> 'payload' -> 'provider_options' ->> 'disable_identity_result_cache',
        'false'
      )) not in ('1', 'true', 'yes', 'on')
        and pg_catalog.lower(coalesce(
          job_item -> 'payload' -> 'provider_options' ->> 'disable_identity_result_cache_read',
          'false'
        )) not in ('1', 'true', 'yes', 'on'),
      pg_catalog.lower(coalesce(
        job_item -> 'payload' -> 'provider_options' ->> 'disable_writer_final_replay',
        'false'
      )) not in ('1', 'true', 'yes', 'on'),
      coalesce(nullif(pg_catalog.btrim(job_item -> 'payload' ->> 'authorized_retry_of_job_id'), ''), ''),
      nullif(pg_catalog.btrim(p_batch ->> 'id'), ''),
      pg_catalog.min(job_item ->> 'id'),
      'queued',
      pg_catalog.clock_timestamp(),
      pg_catalog.clock_timestamp()
    from pg_catalog.jsonb_array_elements(p_jobs) job_item
    join pg_catalog.jsonb_array_elements(coalesce(v_result -> 'jobs', '[]'::jsonb)) result_item
      on result_item -> 'row' ->> 'id' = job_item ->> 'id'
    where coalesce((result_item ->> 'saved')::boolean, false)
      and pg_catalog.upper(coalesce(result_item -> 'row' ->> 'status', '')) in ('QUEUED', 'RETRYING', 'RUNNING')
      and nullif(pg_catalog.btrim(job_item -> 'payload' ->> 'image_generation_id'), '') is not null
      and nullif(pg_catalog.btrim(job_item -> 'payload' ->> 'image_set_sha256'), '') ~ '^[0-9a-fA-F]{64}$'
      and nullif(pg_catalog.btrim(job_item -> 'payload' ->> 'queue_decision_fingerprint'), '') ~ '^[0-9a-fA-F]{64}$'
    group by
      job_item ->> 'asset_id',
      pg_catalog.btrim(job_item -> 'payload' ->> 'image_generation_id'),
      pg_catalog.lower(pg_catalog.btrim(job_item -> 'payload' ->> 'image_set_sha256')),
      pg_catalog.lower(pg_catalog.btrim(job_item -> 'payload' ->> 'queue_decision_fingerprint')),
      pg_catalog.lower(nullif(pg_catalog.btrim(job_item -> 'payload' ->> 'identity_result_cache_key'), '')),
      pg_catalog.lower(nullif(pg_catalog.btrim(job_item -> 'payload' ->> 'identity_cache_image_generation_hash'), '')),
      pg_catalog.lower(coalesce(job_item -> 'payload' -> 'provider_options' ->> 'disable_identity_result_cache', 'false')),
      pg_catalog.lower(coalesce(job_item -> 'payload' -> 'provider_options' ->> 'disable_identity_result_cache_read', 'false')),
      pg_catalog.lower(coalesce(job_item -> 'payload' -> 'provider_options' ->> 'disable_writer_final_replay', 'false')),
      coalesce(nullif(pg_catalog.btrim(job_item -> 'payload' ->> 'authorized_retry_of_job_id'), ''), '')
    on conflict (
      tenant_id,
      asset_id,
      image_generation_id,
      image_set_sha256,
      queue_decision_fingerprint,
      authorized_retry_of_job_id
    )
    do update set
      recognition_batch_id = excluded.recognition_batch_id,
      recognition_job_id = excluded.recognition_job_id,
      identity_result_cache_key = coalesce(outbox.identity_result_cache_key, excluded.identity_result_cache_key),
      identity_cache_image_generation_hash = coalesce(
        outbox.identity_cache_image_generation_hash,
        excluded.identity_cache_image_generation_hash
      ),
      identity_cache_read_allowed = outbox.identity_cache_read_allowed and excluded.identity_cache_read_allowed,
      writer_final_replay_allowed = outbox.writer_final_replay_allowed and excluded.writer_final_replay_allowed,
      status = case
        when outbox.status in ('completed', 'processing', 'dead_letter') then outbox.status
        else 'queued'
      end,
      next_attempt_at = case
        when outbox.status in ('completed', 'processing', 'dead_letter') then outbox.next_attempt_at
        else pg_catalog.clock_timestamp()
      end,
      lease_owner = case when outbox.status = 'processing' then outbox.lease_owner else null end,
      lease_expires_at = case when outbox.status = 'processing' then outbox.lease_expires_at else null end,
      last_error = case when outbox.status in ('completed', 'processing', 'dead_letter') then outbox.last_error else null end,
      updated_at = pg_catalog.clock_timestamp()
    where (outbox.identity_result_cache_key is null
        or excluded.identity_result_cache_key is null
        or outbox.identity_result_cache_key = excluded.identity_result_cache_key)
      and (outbox.identity_cache_image_generation_hash is null
        or excluded.identity_cache_image_generation_hash is null
        or outbox.identity_cache_image_generation_hash = excluded.identity_cache_image_generation_hash);
    get diagnostics v_outbox_count = row_count;
    if v_outbox_count <> v_expected_outbox_count then
      raise exception using
        errcode = '23505',
        message = 'preingestion_recognition_outbox_identity_conflict';
    end if;
  end if;
  return v_result || pg_catalog.jsonb_build_object(
    'queue_enqueue_contract_version', 'v4-queue-identity-outbox-v1',
    'preingestion_commit_intent_count', v_outbox_count
  );
end;
$$;

